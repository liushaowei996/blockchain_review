"""Generate a section-highlighted first-revision TeX copy from the clean source.

Blue denotes the rewritten abstract, section text and revised data
statements. This is not a word-level redline; removed text is omitted.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / "manuscript/main.tex").read_text(encoding="utf-8")
source = source.replace(
    r"\usepackage{needspace}",
    r"\usepackage{needspace}" + "\n" + r"\definecolor{revisionblue}{RGB}{0,70,160}",
    1,
)
abstract = re.search(r"\\abstract\{(.*?)\}\s*\\keyword", source, re.S).group(1)
source = source.replace(
    r"\abstract{" + abstract + "}",
    r"\abstract{\texorpdfstring{\textcolor{revisionblue}{" + abstract + "}}{" + abstract + "}}",
    1,
)
source = source.replace(
    r"\begin{document}",
    r"\begin{document}" + "\n\n" +
    r"\noindent{\small\textit{Revision copy: rewritten body text is blue. Figures and tables retain publication styling. Removed text is omitted; this is not a word-level redline.}}\par\medskip",
    1,
)
source = re.sub(
    r"\\input\{sections/[^}]+\}",
    lambda m: r"\begingroup\color{revisionblue}" + m.group(0) + r"\endgroup",
    source,
)
for macro in ("supplementary", "dataavailability"):
    source = source.replace("\\" + macro + "{", "\\" + macro + "{\\color{revisionblue} ", 1)
target = ROOT / "manuscript/main-marked.tex"
target.write_text("% Generated by scripts/build_revision_marked.py.\n" + source, encoding="utf-8")
print(target)
